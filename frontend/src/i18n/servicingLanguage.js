const BN_ALL = Object.freeze({ ...BN, ...BN_MORE })
const BN_LOWER = new Map(Object.entries(BN_ALL).map(([key, value]) => [key.toLocaleLowerCase('en'), value]))

const UI_LABEL_PREFIXES = new Set([
  'customer', 'customer name', 'mobile', 'mobile number', 'phone number',
  'service job', 'job', 'status', 'technician', 'device', 'serial number',
  'serial no', 'device serial', 'price', 'selling price', 'buying price',
  'quantity', 'qty', 'amount', 'total', 'balance', 'warehouse', 'company',
  'supplier', 'receipt', 'item code', 'date', 'cashier', 'currency'
])

function findBanglaEnglishLabel(raw) {
  if (typeof raw !== 'string') return null
  const s = raw.trim().replace(/\s+/g, ' ').replace(/\u00a0/g, ' ')
  if (!s || s.length > 600) return null
  if (Object.prototype.hasOwnProperty.call(BN_ALL, s)) return BN_ALL[s]
  const byCase = BN_LOWER.get(s.toLocaleLowerCase('en'))
  if (byCase) return byCase

  // "Customer:" or "Status:" are display labels even when the value is a
  // different Vue text node. Never alter the stored value after the colon.
  if (s.endsWith(':')) {
    const key = s.slice(0, -1).trim()
    if (UI_LABEL_PREFIXES.has(key.toLocaleLowerCase('en'))) {
      const name = BN_LOWER.get(key.toLocaleLowerCase('en'))
      if (name) return name + ':'
    }
  }
  const prefix = /^([A-Za-z][A-Za-z /&.()-]{1,34}):\s*(.+)$/.exec(s)
  if (prefix && UI_LABEL_PREFIXES.has(prefix[1].toLocaleLowerCase('en'))) {
    const name = BN_LOWER.get(prefix[1].toLocaleLowerCase('en'))
    if (name) return name + ': ' + prefix[2]
  }

  // Common Vue-generated counters. Keep their numbers unchanged.
  let match = /^(\d[\d,]*)\s+shown$/i.exec(s)
  if (match) return match[1] + 'টি দেখানো হচ্ছে'
  match = /^Showing\s+(\d[\d,]*)\s+of\s+(\d[\d,]*)$/i.exec(s)
  if (match) return match[2] + 'টির মধ্যে ' + match[1] + 'টি দেখানো হচ্ছে'
  match = /^(\d[\d,]*)\s+(items|products|laptops|jobs|records|customers)\s+(found|shown)$/i.exec(s)
  if (match) {
    const nouns = { items: 'পণ্য', products: 'পণ্য', laptops: 'ল্যাপটপ', jobs: 'জব', records: 'রেকর্ড', customers: 'ক্রেতা' }
    return match[1] + 'টি ' + nouns[match[2].toLowerCase()] + (match[3].toLowerCase() === 'found' ? ' পাওয়া গেছে' : ' দেখানো হচ্ছে')
  }
  return null
}

const originalText = new WeakMap()
const originalAttributes = new WeakMap()
const ATTRS = ['placeholder', 'title', 'aria-label', 'alt']
let observer = null
const pending = new Set()
let scheduled = false

function skipped(node) {
  const el = node?.nodeType === 1 ? node : node?.parentElement
  if (!el || !el.closest) return true
  if (el.closest('script,style,code,pre,textarea,svg,math,[contenteditable="true"],[translate="no"],[data-no-translate],[data-sos-language-control]')) return true
  // Do not alter the document used to print invoices and device labels.
  if (el.closest('[data-receipt-print],[data-thermal-print],[data-print-root]')) return true
  if (el.closest('option:not([value])')) return true
  return false
}

function translated(text) {
  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/)
  const replacement = findBanglaEnglishLabel(text)
  if (!replacement) return null
  return (match?.[1] || '') + replacement + (match?.[3] || '')
}

function updateText(node) {
  if (!node || node.nodeType !== 3 || !node.parentElement || skipped(node)) return
  const value = node.nodeValue || ''
  let state = originalText.get(node)
  if (!state) { state = { base: value, last: value }; originalText.set(node, state) }
  else if (value !== state.last) { state.base = value; state.last = value }
  const target = currentLanguage.value === 'bn' ? (translated(state.base) ?? state.base) : state.base
  if (target !== value) node.nodeValue = target
  state.last = target
}

function updateAttrs(node) {
  if (!node || node.nodeType !== 1 || skipped(node)) return
  let state = originalAttributes.get(node)
  if (!state) { state = {}; originalAttributes.set(node, state) }
  for (const attr of ATTRS) {
    if (!node.hasAttribute(attr)) continue
    const now = node.getAttribute(attr) || ''
    const prev = state[attr]
    if (!prev || now !== prev.last) state[attr] = { base: now, last: now }
    const saved = state[attr]
    const target = currentLanguage.value === 'bn' ? (translated(saved.base) ?? saved.base) : saved.base
    if (target !== now) node.setAttribute(attr, target)
    saved.last = target
  }
}

function walk(root) {
  if (!root || skipped(root)) return
  if (root.nodeType === 3) { updateText(root); return }
  if (root.nodeType !== 1 && root.nodeType !== 9) return
  if (root.nodeType === 1) updateAttrs(root)
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT)
  while (walker.nextNode()) {
    const n = walker.currentNode
    if (skipped(n)) continue
    if (n.nodeType === 3) updateText(n)
    else updateAttrs(n)
  }
}

function flush() {
  scheduled = false
  if (typeof document === 'undefined') return
  const nodes = [...pending]
  pending.clear()
  for (const node of nodes) if (node.isConnected || node === document.body) walk(node)
}
function schedule(node) {
  if (node) pending.add(node)
  if (scheduled) return
  scheduled = true
  // Batch updates from Vue renders, without polling or network calls.
  if (typeof requestAnimationFrame === 'function') requestAnimationFrame(flush)
  else Promise.resolve().then(flush)
}

export function setLanguage(code) {
  if (code !== 'en' && code !== 'bn') return
  currentLanguage.value = code
  try { localStorage.setItem(KEY, code) } catch (_) { /* private mode */ }
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', code)
    document.documentElement.setAttribute('data-servicing-lang', code)
    schedule(document.body)
  }
}
export function uiText(value) {
  const s = String(value ?? '')
  if (currentLanguage.value !== 'bn') return s
  return findBanglaEnglishLabel(s) ?? s
}

